#!/usr/bin/env node
'use strict';

// Configure a locally installed, user-accepted Java ME SDK. This helper never
// downloads or redistributes Oracle binaries; it only validates and records paths.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { inspectApiArchive, isExecutableFile } = require('./check-j2me-toolchain');
const { verifyArtifact } = require('./acquire-ecj');

const CLDC_REQUIRED = [
  'java/lang/Object.class',
  'javax/microedition/io/Connection.class',
  'javax/microedition/io/Connector.class'
];
const MIDP_REQUIRED = [
  'javax/microedition/midlet/MIDlet.class',
  'javax/microedition/lcdui/Display.class',
  'javax/microedition/lcdui/Canvas.class',
  'javax/microedition/rms/RecordStore.class',
  'javax/microedition/rms/RecordEnumeration.class'
];
const CLDC_NAMES = new Set(['cldcapi11.jar', 'cldcapi.jar']);
const MIDP_NAMES = new Set(['midpapi20.jar', 'midpapi.jar']);
const PREVERIFY_NAMES = new Set(process.platform === 'win32'
  ? ['preverify.exe', 'preverify.bat'] : ['preverify', 'preverify.sh']);

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const key = argv[i];
    if (['--root', '--ecj', '--output'].includes(key)) {
      if (!argv[i + 1]) throw new Error(`${key} requires a path`);
      args[key.slice(2)] = path.resolve(argv[++i]);
    } else if (key === '--help') args.help = true;
    else throw new Error(`Unknown argument: ${key}`);
  }
  return args;
}

function walkFiles(root, maxDepth = 8) {
  const files = [];
  const seen = new Set();
  function visit(dir, depth) {
    if (depth > maxDepth) return;
    let real;
    try { real = fs.realpathSync(dir); } catch (_) { return; }
    if (seen.has(real)) return;
    seen.add(real);
    let entries;
    try { entries = fs.readdirSync(real, { withFileTypes: true }); } catch (_) { return; }
    for (const entry of entries) {
      const full = path.join(real, entry.name);
      if (entry.isFile()) files.push(full);
      else if (entry.isDirectory() && !entry.isSymbolicLink() &&
        !['.git', 'node_modules', 'proc', 'sys', 'dev'].includes(entry.name)) visit(full, depth + 1);
    }
  }
  visit(root, 0);
  return files;
}

function findByName(files, names) {
  return files.find(file => names.has(path.basename(file).toLowerCase())) || '';
}

function propertyPath(file) {
  // Forward slashes avoid Java-properties escape ambiguity on Windows.
  return path.resolve(file).replace(/\\/g, '/').replace(/([:=])/g, '\\$1');
}

function configure({ root, ecj, output = path.resolve('build.properties'), jarCommand = process.env.JAR || 'jar',
  platform = process.platform, runner = spawnSync, ecjVerifier = verifyArtifact } = {}) {
  if (!root || !fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
    throw new Error('--root must point to an extracted Java ME SDK/WTK directory');
  }
  const files = walkFiles(root);
  const cldc = findByName(files, CLDC_NAMES);
  const midp = findByName(files, MIDP_NAMES);
  const preverify = findByName(files, PREVERIFY_NAMES);
  const failures = [];
  if (!cldc) failures.push('CLDC API archive not found (cldcapi11.jar)');
  if (!midp) failures.push('MIDP API archive not found (midpapi20.jar)');
  if (!preverify || !isExecutableFile(preverify, platform)) failures.push('Preverifier missing or not executable');
  if (cldc) {
    const result = inspectApiArchive(cldc, CLDC_REQUIRED, jarCommand, runner);
    if (!result.ok) failures.push(`CLDC API validation failed: ${result.detail}`);
  }
  if (midp) {
    const result = inspectApiArchive(midp, MIDP_REQUIRED, jarCommand, runner);
    if (!result.ok) failures.push(`MIDP API validation failed: ${result.detail}`);
  }
  if (!ecj) failures.push('--ecj must point to a locally available ECJ batch compiler JAR');
  else {
    try { ecjVerifier(ecj); }
    catch (error) { failures.push(`ECJ validation failed: ${error.message}`); }
  }
  if (failures.length) {
    const error = new Error(`Local toolchain was not configured:\n- ${failures.join('\n- ')}`);
    error.failures = failures;
    throw error;
  }
  const contents = [
    '# Generated by Netormium configure-local-toolchain.js',
    '# Local paths only; SDK/compiler binaries are not copied into this project.',
    'compiler.backend=ecj',
    `ecj.jar=${propertyPath(ecj)}`,
    `cldc.api.jar=${propertyPath(cldc)}`,
    `midp.api.jar=${propertyPath(midp)}`,
    `preverify.executable=${propertyPath(preverify)}`,
    'javac.source=1.3',
    'javac.target=1.1',
    ''
  ].join('\n');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, contents, { encoding: 'utf8', flag: 'w' });
  return { root: path.resolve(root), ecj: path.resolve(ecj), cldc, midp, preverify, output: path.resolve(output) };
}

function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv);
  if (args.help) {
    console.log('Usage: node scripts/configure-local-toolchain.js --root /path/to/WTK --ecj /path/to/ecj.jar [--output ../build.properties]');
    console.log('Validates local CLDC/MIDP API contents, preverifier, and ECJ before writing build.properties.');
    return;
  }
  const result = configure(args);
  console.log('Local Java ME toolchain configured:');
  for (const [key, value] of Object.entries(result)) console.log(`${key}: ${value}`);
  console.log('Next: ant -propertyfile build.properties clean release');
}

if (require.main === module) {
  try { main(); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { CLDC_REQUIRED, MIDP_REQUIRED, parseArgs, walkFiles, findByName, propertyPath, configure };
